FAMILIES: dict[str, Family] = {f.name: f for f in _TABLE}


def family(problem: str, suite: str | None = None) -> Family:
    """The registered family `problem` (of `suite`, when given); KeyError otherwise."""
    entry = FAMILIES.get(problem)
    if entry is None or (suite is not None and entry.suite != suite):
        raise KeyError(f"unknown {suite + ' ' if suite else ''}problem family: {problem!r}")
    return entry


def problems(suite: str | None = None) -> list[str]:
    """The registered family names (of one suite), in registry order."""
    return [name for name, entry in FAMILIES.items() if suite is None or entry.suite == suite]


def cohort_tracks(families, track: str = SMALL_SCALE) -> dict[str, Track]:
    """{family: its `track` descriptor} for a campaign cohort; every family must have that track wired."""
    tracks = {}
    for name in families:
        entry = FAMILIES[name].tracks.get(track)
        if entry is None or not entry.wired:
            raise KeyError(f"{name} has no wired {track} track")
        tracks[name] = entry
    return tracks


def track_family(tool_key: str, track: str = LARGE_SCALE) -> str:
    """The registry family whose `track` its tools call `tool_key` (large scale: "lbbd" -> "lbbd_ps")."""
    found = [name for name, entry in FAMILIES.items() if entry.tracks.get(track) is not None and entry.tracks[track].tool_key == tool_key]
    if len(found) != 1:
        raise KeyError(f"no single {track} family is called {tool_key!r}")
    return found[0]


def dataset_families(dataset: str) -> list[str]:
    """The families whose final instances live under the repository-relative root `dataset`."""
    return [name for name, entry in FAMILIES.items() if entry.dataset == dataset]


def dataset_roots() -> dict[Path, str]:
    """The resolved pinned dataset roots (the family roots and the combined campaign roots) and their repository-relative names."""
    roots = {(REPOSITORY / entry.dataset).resolve(): entry.dataset for entry in FAMILIES.values()}
    roots.update({(REPOSITORY / name).resolve(): name for name in CAMPAIGN_DATASETS})
    return roots
