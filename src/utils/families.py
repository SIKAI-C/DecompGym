@dataclass(frozen=True)
class Family:
    name: str
    suite: str  # "bd" (Benders decomposition) or "cg" (column generation)
    label: str  # human-readable name (dashboard)
    generator: str  # a_gen_data function (seed, size, output_dir) -> data.json payload, or (payload, recipe fields)
    monolithic: str  # "module.Class" of the monolithic MIP, relative to src/<suite>/<name>
    reference: str  # "module.Class" of the decomposition reference
    dataset: str
    config: str
    contract: str
    admission: str = "strict"
    meta_layout: str = "source_summary"  # the meta.json layout (instance_suite.META_LAYOUTS)
    recipe: str | None = None  # a_gen_data function (seed, size) -> recipe fields recorded in meta.json
    reference_options: MappingProxyType = field(default_factory=lambda: MappingProxyType({}))  # besides time_limit
    reference_certified: bool = False  # admission also needs the reference's own optimality certificate
    tol: float = 1e-6  # relative tolerance of certificates and of the reference-below-optimum check
    mip_time_limit: float = 1800.0  # Gurobi TimeLimit of the monolithic MIP during generation
    full_verifier: bool = False  # bd only: d_verifier checks the whole plan (no shared y/x domain check)
    sizes: tuple[str, ...] = SIZES

    @property
    def module(self) -> str:
        return f"src.{self.suite}.{self.name}"

    @property
    def verifier(self) -> str:
        return f"src/{self.suite}/{self.name}/d_verifier.py"

    @property
    def prompt(self) -> str:
        return f"{self.module}.b_problem"

    def reference_class(self, method: str) -> str:
        if method not in {"monolithic", "decomposition"}:
            raise ValueError("method must be monolithic or decomposition")
        return self.monolithic if method == "monolithic" else self.reference

    @property
    def tracks(self) -> Mapping[str, Track | None]:
        """{SMALL_SCALE: the wired small-scale track, LARGE_SCALE: its descriptor or None}."""
        modules = tuple(dict.fromkeys(("a_gen_data", self.monolithic.split(".")[0], self.reference.split(".")[0], "b_problem", "c_gen", "d_verifier")))
        small = Track(SMALL_SCALE, self.name, f"src/{self.suite}/{self.name}", modules, self.name, sizes=self.sizes, seeds=SEEDS, dataset=self.dataset, config=self.config, wired=True)
        large = _LARGE_SCALE.get(self.name)
        if large is not None:
            location, tool_key, names = large
            large = Track(LARGE_SCALE, self.name, location, names, tool_key)
        return MappingProxyType({SMALL_SCALE: small, LARGE_SCALE: large})


