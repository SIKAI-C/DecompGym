"""The problem families of DecompGym in one table: generator, references, verifier, prompt, dataset and admission.

Every family lives in src/<suite>/<name>/ with the same file roles:
  a_gen_data.py   the instance generator (`generator`; `recipe` when the recipe fields go to meta.json)
  a_gold_monolithic.py / a_gold_<suite>.py (UFL: b_gold_*)   the monolithic MIP and the decomposition reference
  b_problem.py    the task-prompt template (render_prompt)
  c_gen.py        generate_suite: data, prompt, verified references and meta.json (src.utils.instance_suite)
  d_verifier.py   the harness verifier of an agent's output.json
Large-scale (scale-up) modules of a family carry an _xl suffix or are listed by the large-scale tools.

`dataset` is the repository-relative root of the family's final instances and `config` the campaign config whose cohort
includes them; `contract` is the decomposition contract its prompt.txt files are rendered with.

The small-scale campaign (SMALL_SCALE_CONFIG) runs every registered family from one combined root,
SMALL_SCALE_CAMPAIGN_DATA (scripts/build_small_scale_data.py): byte-identical copies of each family's final instances
from its `dataset`, with prompt.txt re-rendered under the campaign's contract. It is pinned like the family roots
(dataset_roots) but holds no family's `dataset`, so src.utils.dataset.instance_admission applies each family's own rule.

Tracks (`tracks`, keyed SMALL_SCALE and LARGE_SCALE): each family describes its tracks with explicit descriptors. The
small-scale descriptor is the data above (sizes x SEEDS, dataset, config, the module roles listed above) and is the one
the paired runner and the campaign read (campaign init and check-config take instance counts and sizes from it). The
large-scale slot is None, or a descriptor that only points at the family's existing large-scale modules (wired=False:
registry support is not campaign eligibility). A track records its semantic family identity: the large-scale modules
in src/bd/lbbd/*_xl.py model cumulative planning and scheduling, so they are the large-scale track of lbbd_ps (their
tools call them "lbbd"); the registry's lbbd is the small-scale assignment and tardiness family and has no large-scale
track. No family is renamed and no small-scale id changes.

Admission (`admission`, see src.utils.instance_suite):
  "strict"               one rule for every family generated by instance_suite with the current recipes;
  "mip_or_certificate"   the historical rule of the reused instances of lbbd, gcol and nrp (configs/harder_small_all.json);
  "family"               the family's own c_gen pipeline (tsso, lrp, shift: the paper's instances, configs/paper.json).
The reused (Group A) families keep their historical settings so that their instances regenerate identically.
"""
