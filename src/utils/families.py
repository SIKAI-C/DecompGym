@dataclass(frozen=True)
class Track:
    """One track of a family: where its modules live and, once wired, which instances a campaign of it holds."""
    name: str  # SMALL_SCALE or LARGE_SCALE
    family: str  # the semantic family identity (the registry name) of the track's instances
    location: str  # repository-relative package of the track's modules
    modules: tuple[str, ...]  # the track's module files (without .py) in `location`
    tool_key: str  # the name the track's own tools use for it
    sizes: tuple[str, ...] = ()
    seeds: tuple[int, ...] = ()
    dataset: str | None = None
    config: str | None = None
    wired: bool = False  # True: the paired runner and the campaign controller run this track

    @property
    def instance_count(self) -> int:
        return len(self.sizes) * len(self.seeds)

    def instance_name(self, size: str, seed: int) -> str:
        return f"{self.family}_{size}_seed{seed:03d}"


