"""Two-stage stochastic capacitated facility location (SCFL) at small scale.

Semantics follow the scale-up SCFL (Louveaux 1986; Bodur, Dash, Guenluek and Luedtke 2017, INFORMS JoC 29(1):77-91,
formulation (15)):
    first stage   open facilities y_i in {0, 1} (fixed cost f_i, capacity u_i) with sum_i u_i y_i >= max_s sum_j d_sj;
    second stage  per scenario s (probability p_s): x_sij >= 0, sum_i x_sij = d_sj, sum_j x_sij <= u_i y_i,
                  cost Q_s(y) = min sum_ij c_ij x_sij;
    minimize      f.y + sum_s p_s Q_s(y).
((15b) is written with >=; with c >= 0 an optimal recourse never over-serves, so = is equivalent.)

Recipe: Bodur et al. (2017), Section 4.4: "We take the deterministic CAP instances from J. E. Beasley's OR-Library
(Beasley 1990) that have 50 customers and 25-50 potential facilities [cap101-cap134] ... We take for each j,
mu_j = lambda_bar_j, and sigma_j ~ U(0.1 lambda_bar_j, 0.3 lambda_bar_j) ... and generate stochastic demands
lambda_j ~ N(mu_j, sigma_j)", equal scenario probabilities 1/|K| (objective (15a)); the paper uses |K| = 250, 500,
1500. The CAP files (vendored unchanged in src/bd/scfl/orlib_cap/, sha256-pinned below; OR-Library,
http://people.brunel.ac.uk/~mastjjb/jeb/orlib/capinfo.html) give u_i, f_i, lambda_bar_j and the cost of serving ALL
of customer j from facility i.
Conversion and rounding, shared with the scale-up generator (src/bd/scfl/a_data.py: read_orlib_cap,
make_stochastic, which this module calls unchanged): unit cost c_ij = alloc_cost_ij / lambda_bar_j (IEEE double,
written with repr, not rounded); demands rounded to the nearest integer and truncated at 0; the scenario stream is
numpy default_rng(seed) (sigma first, then the S x J demand matrix in row order).
Small-scale adaptation (named; Bodur et al. use |K| = 250-1500, too many for a 60 s reference decomposition):
  1. base: one of the 8 capacitated files cap111-cap124 (50 facilities, 50 customers, u_i = 5000 or 15000, fixed
     costs 7500 / 12500 / 17500 / 25000), drawn uniformly with numpy default_rng([seed, 0x5CF1]). cap101-104 and
     cap131-134 are excluded by a structural rule: there u_i = 58268 = the total mean demand, so capacities almost
     never bind and the instance reduces to a stochastic uncapacitated problem (pilot extensive forms had LP = MIP);
  2. the whole base is used (no facility or customer subsampling), so f, u, c and lambda_bar are the published data;
  3. S = 20 / 35 / 55 scenarios (SIZE_CONFIG) instead of 250-1500, generated by make_stochastic(base, S, seed)
     exactly as at scale; S is bounded by the 60 s Benders reference budget, not by the MIP (proved within 1800 s).
An instance whose total capacity is below a scenario demand raises (no redraw; normal demands are not truncated above,
so this is possible in principle, but no pilot or evaluation draw has hit it).
Every CAP unit cost alloc/lambda_bar is a multiple of 1/80 (up to the double conversion), so design values lie on a
1/(80 S) lattice and the references certify exact optimality on it (see a_gold_monolithic).
"""
