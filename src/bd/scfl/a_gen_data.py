@dataclass
class SCFLInstance(JsonDataMixin):
    n_facilities: int
    n_customers: int
    n_scenarios: int
    capacity: list[int]           # u_i
    fixed_cost: list[float]       # f_i
    unit_cost: list[list[float]]  # c_ij, n_facilities x n_customers
    demand: list[list[int]]       # d_sj, n_scenarios x n_customers
    probability: list[float]      # p_s

    def __post_init__(self) -> None:
        I, J, S = self.n_facilities, self.n_customers, self.n_scenarios
        if len(self.capacity) != I or len(self.fixed_cost) != I or len(self.unit_cost) != I or any(len(r) != J for r in self.unit_cost):
            raise ValueError("facility data must have n_facilities entries (unit_cost rows of n_customers)")
        if len(self.demand) != S or any(len(r) != J for r in self.demand) or len(self.probability) != S:
            raise ValueError("demand must be n_scenarios x n_customers and probability of length n_scenarios")

    @classmethod
    def from_json_file(cls, path: str | Path) -> SCFLInstance:
        return cast("SCFLInstance", super().from_json_file(path))

    @property
    def max_demand(self) -> int:
        return max(sum(row) for row in self.demand)


def load_cap_base(name: str) -> dict:
    """A vendored OR-Library CAP file, checked against its pinned sha256 and parsed by the scale-up reader."""
    path = ORLIB_DIR / f"{name}.txt"
    if hashlib.sha256(path.read_bytes()).hexdigest() != CAP_SHA256[name]:
        raise ValueError(f"{path}: sha256 differs from the pinned OR-Library file")
    return read_orlib_cap(path)


def generate_scfl_instance(seed: int, size: str = "medium", output_dir: str | Path | None = None) -> dict[str, Any]:
    if size not in SIZE_CONFIG:
        raise ValueError(f"Unknown size_label '{size}'. Expected one of {list(SIZE_CONFIG)}.")
    S = SIZE_CONFIG[size]["n_scenarios"]
    rng = np.random.default_rng([seed, 0x5CF1])
    base_name = CAPACITATED_BASES[int(rng.integers(len(CAPACITATED_BASES)))]
    base = load_cap_base(base_name)
    sto = make_stochastic(base, S, seed)  # the scale-up generator itself: conversion, rounding and stream
    I, J = sto.I, sto.J
    inst = SCFLInstance(I, J, S, [int(v) for v in sto.capacity], [float(v) for v in sto.fixed],
                        [[float(v) for v in row] for row in sto.cost], [[int(v) for v in row] for row in sto.demand],
                        [1.0 / S] * S)
    if output_dir is not None:
        out_dir = Path(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        inst.to_json_file(out_dir / "data.json")
        # Provenance stays out of data.json (the only file the agent sees).
        source = {"recipe": "Bodur et al. (2017) Sec. 4.4 scenarios on an OR-Library CAP base", "base": base_name,
                  "n_scenarios": S, "base_stream": f"default_rng([{seed}, 0x5CF1])", "scenario_stream": f"make_stochastic(seed={seed})"}
        (out_dir / "source.json").write_text(json.dumps(source, indent=2))
    return inst.to_dict()
