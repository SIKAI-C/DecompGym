"""Teaching charts for the README's problem formulations: reference bound and column progress from the saved reference records in data/.

    python -m src.results.teaching_figures      # writes assets/formulations/*.png; no model is solved
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator
import numpy as np


REPOSITORY = Path(__file__).resolve().parents[2]


# ColorBrewer Paired, four classes, rated colorblind safe. Dark colors are used
# for lines; light partners are reserved for fills. Line styles also encode roles.
PALETTE = ("#a6cee3", "#1f78b4", "#b2df8a", "#33a02c")
MASTER_COLOR = PALETTE[1]
SECOND_COLOR = PALETTE[3]
EXAMPLES = {
    "bd": {"ufl": "small", "fctp": "large", "km": "small", "lrp": "small", "tsso": "small"},
    "cg": {"bp": "small", "csp": "small", "gap": "small", "shift": "small"},
}


def _finish(fig: plt.Figure, axes: np.ndarray, target: Path) -> None:
    for axis in axes:
        axis.set_xlabel("Iteration")
        axis.xaxis.set_major_locator(MaxNLocator(integer=True))
        axis.grid(axis="y", color="#e2e5e9", linewidth=0.7)
        axis.set_axisbelow(True)
        axis.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(pad=1.2, rect=(0, 0, 1, 0.92))
    fig.savefig(target, dpi=160, facecolor="white")
    plt.close(fig)


def draw_benders(result: dict, problem: str, instance: str, target: Path) -> None:
    rows = result["iter_records"]
    iterations = np.asarray([row["iteration"] for row in rows])
    fig, axes = plt.subplots(1, 2, figsize=(10.4, 3.8))
    lower = np.asarray([row["global_lb"] for row in rows], dtype=float)
    upper = np.asarray([row["global_ub"] for row in rows], dtype=float)
    finite_lower, finite_upper = np.isfinite(lower), np.isfinite(upper)
    axes[0].plot(iterations[finite_lower], lower[finite_lower], color=MASTER_COLOR, linewidth=2, marker="o" if len(rows) < 12 else None, label="Master lower bound")
    axes[0].plot(iterations[finite_upper], upper[finite_upper], color=SECOND_COLOR, linewidth=2, linestyle="--", marker="s" if len(rows) < 12 else None, label="Best integer solution cost")
    finite_iterations = iterations[finite_lower | finite_upper]
    if len(finite_iterations):
        axes[0].set_xlim(finite_iterations.min() - 0.5, iterations.max() + 0.5)
    axes[0].set_title("Master bound and feasible solution")
    axes[0].set_ylabel("Objective value")
    axes[0].legend(fontsize=9, loc="best")
    axes[1].step(iterations, [row["n_feas_cuts"] for row in rows], where="mid", color=MASTER_COLOR, linewidth=1.8, label="Feasibility cuts")
    axes[1].step(iterations, [row["n_opt_cuts"] for row in rows], where="mid", color=SECOND_COLOR, linewidth=1.8, linestyle="--", label="Optimality cuts")
    axes[1].set_title("Cuts generated by the subproblem")
    axes[1].set_ylabel("Cuts in this iteration")
    axes[1].yaxis.set_major_locator(MaxNLocator(integer=True))
    axes[1].legend(fontsize=9, loc="best")
    fig.suptitle(f"{problem.upper()} reference solver: {instance}", fontsize=12)
    _finish(fig, axes, target)


def draw_columns(result: dict, problem: str, instance: str, target: Path) -> None:
    rows = result["iter_records"]
    iterations = [row["iteration"] for row in rows]
    fig, axes = plt.subplots(1, 3, figsize=(12.6, 3.8))
    axes[0].plot(iterations, [row["master_obj"] for row in rows], color=MASTER_COLOR, linewidth=2, marker="o")
    axes[0].set_title("Restricted master LP")
    axes[0].set_ylabel("Objective value")
    axes[1].plot(iterations, [row["reduced_cost"] for row in rows], color=SECOND_COLOR, linewidth=2, marker="s")
    axes[1].axhline(0, color="#4b5563", linewidth=1, linestyle="--")
    axes[1].set_title("Pricing: negative means improving")
    axes[1].set_ylabel("Best reported reduced cost")
    axes[2].step(iterations, [row["n_patterns"] for row in rows], where="mid", color=MASTER_COLOR, linewidth=2, marker="o")
    axes[2].set_title("Columns available to the master")
    axes[2].set_ylabel("Number of columns")
    axes[2].yaxis.set_major_locator(MaxNLocator(integer=True))
    fig.suptitle(f"{problem.upper()} reference solver: {instance}", fontsize=12)
    _finish(fig, axes, target)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, default=REPOSITORY / "data")
    parser.add_argument("--output", type=Path, default=REPOSITORY / "assets/formulations")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.titlesize": 10, "axes.labelsize": 10})
    for suite, problems in EXAMPLES.items():
        for problem, size in problems.items():
            instance = f"{problem}_{size}_seed000"
            source = args.data_root / suite / problem / instance / f"gold_{suite}.json"
            result = json.loads(source.read_text())
            target = args.output / f"{suite}_{problem}_progress.png"
            draw = draw_benders if suite == "bd" else draw_columns
            draw(result, problem, instance, target)
            print(f"Saved {target} from {source}")


if __name__ == "__main__":
    main()
