"""Publish the paper results to the tracked results/ folder: PNG figures, LaTeX tables, prompt examples and a summary page."""
from __future__ import annotations

import json
from pathlib import Path
import shutil

from src.results.paper_figures import TABLE_BUDGETS, label
from src.results.combine import points


FIGURES = (
    ("attempt_quality", "Quality success Q@k by attempt budget, without (left) and with (right) reflection."),
    ("stage_success", "The three criteria by attempt budget: executable (E), verified (V) and quality (Q)."),
    ("reflection_gain", "Additional instances solved with reflection at budgets 2 and 3."),
    ("family_first", "First-attempt successes per configuration and problem family."),
    ("failure_first", "First failed check of each first attempt, by method."),
    ("failure_retry", "First failed check of each retry, by policy."),
    ("agent_time", "Quality success by cumulative agent time."),
    ("agent_tokens", "Quality success by cumulative context + output tokens."),
    ("cost_breakdown", "Mean active time per instance by stage."),
)


def heading(k, mode):
    return f"Q@{k}" if k == 1 else f"Q@{k} {'P' if mode == 'plain' else 'R'}"


def main_table(data):
    lines = ["| Configuration | " + " | ".join(heading(k, mode) for k, mode in TABLE_BUDGETS) + " |", "|---|" + "---:|" * len(TABLE_BUDGETS)]
    totals = [0] * len(TABLE_BUDGETS)
    for model in data["primary_models"]:
        rows = points(data, model)
        counts = [rows[k - 1][mode + "_successes"] for k, mode in TABLE_BUDGETS]
        totals = [a + b for a, b in zip(totals, counts)]
        lines.append(f"| {label(model)} | " + " | ".join(f"{100 * n / 81:.1f}%" for n in counts) + " |")
    pairs = 81 * len(data["primary_models"])
    lines.append("| **All (972 pairs)** | " + " | ".join(f"**{100 * n / pairs:.1f}%**" for n in totals) + " |")
    return "\n".join(lines)


def staged_table(data):
    lines = ["| Criterion | " + " | ".join(heading(k, mode).replace("Q", "") for k, mode in TABLE_BUDGETS) + " |", "|---|" + "---:|" * len(TABLE_BUDGETS)]
    for metric, title in (("execution", "E: executable"), ("verification", "V: verified"), ("quality", "Q: quality")):
        own = [r for r in data["rows"] if r["model"] in data["primary_models"] and r["dimension"] == "overall" and r["metric"] == metric]
        lines.append(f"| {title} | " + " | ".join(str(sum(r[mode + "_successes"] for r in own if r["budget"] == k)) for k, mode in TABLE_BUDGETS) + " |")
    return "\n".join(lines)


def publish(out: Path, results: Path):
    """Copy the small artifacts into results/ and write results/README.md from the same data."""
    data = json.loads((out / "combined.json").read_text())
    for folder, pattern in (("figures", "*.png"), ("tables", "*.tex"), ("prompts", "*.txt")):
        target = results / folder
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True)
        for path in sorted((out / folder).glob(pattern)):
            shutil.copyfile(path, target / path.name)
    shutil.copyfile(out / "results_provenance.json", results / "provenance.json")
    figures = "\n\n".join(f"![{text}](figures/{name}.png)\n\n*{text}*" for name, text in FIGURES)
    page = f"""# Paper results

Generated by `python src/03_analysis.py` from the two audited paper campaigns (12 configurations × 81 instances = 972 paired runs). Do not edit by hand.

Q@k is the share of instances with at least one attempt among the first k that runs, passes the feasibility check and the method audit, and is within 1% of the reference objective. P = plain regeneration, R = reflection; the first attempt is shared.

## Quality success

{main_table(data)}

## Executable, verified and quality successes (counts of 972)

{staged_table(data)}

## Figures

{figures}

LaTeX tables are in [tables/](tables/), the prompt examples of the paper appendix in [prompts/](prompts/), and hashes of every input and output in [provenance.json](provenance.json).
"""
    (results / "README.md").write_text(page)
    return results
