"""The website data (site/data.js) matches the saved paper report.

Runs only when outputs/reports/paper is present; it reads saved JSON and never calls a model or a solver.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from src.results import site

REPOSITORY = Path(__file__).resolve().parents[1]
REPORT = REPOSITORY / "outputs" / "reports" / "paper"


def test_site_page_and_data_files_exist():
    page = (REPOSITORY / "site" / "index.html").read_text()
    assert '<script src="data.js"></script>' in page and "benchmark_overview.png" in page
    assert (REPOSITORY / "site" / "data.js").read_text().startswith("// Generated by src/results/site.py")


@pytest.mark.skipif(not (REPORT / "combined.json").exists(), reason="paper report not built")
def test_site_data_matches_the_paper_report():
    # Source hashes change whenever the report is rebuilt (timestamps); everything else must be identical.
    text = (REPOSITORY / "site" / "data.js").read_text()
    saved = json.loads(text[text.index("=") + 1:].strip().rstrip(";"))
    fresh = site.site_data(REPORT)
    for data in (saved, fresh):
        data["meta"].pop("sources")
    assert saved == fresh
